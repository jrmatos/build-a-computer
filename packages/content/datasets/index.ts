import { digits } from './digits';
import { TEXT_DATASETS } from './text/index';

/**
 * Datasets that Track 2 levels provide through the 'data' module, by id
 * (JsSetup.datasets). Each entry has its license record (E-ML-07; the full
 * table is LICENSES.md) and a loader. Every dataset here is generated in code
 * from a fixed seed, so nothing is downloaded and every load is identical.
 */

export interface DatasetEntry {
  meta: {
    id: string;
    title: string;
    /** SPDX license id. */
    license: string;
    /** Where it comes from (generated, or the fetched source URL). */
    source: string;
    /** Approximate size as JSON, in bytes (plan: at most 20 MB per level). */
    sizeBytes: number;
  };
  /** Structured-clone-safe data, as the player receives it from `load(id)`. */
  load: () => unknown;
}

export const DATASETS: Record<string, DatasetEntry> = {
  'digits-8x8': {
    meta: {
      id: 'digits-8x8',
      title: 'Synthetic 8×8 digits (1,500 train / 300 test)',
      license: 'CC0-1.0',
      source: 'generated by packages/content/datasets/digits.ts',
      sizeBytes: 500_000,
    },
    load: () => {
      const d = digits();
      return { side: d.side, classes: d.classes, train: d.train, test: d.test };
    },
  },
  ...TEXT_DATASETS,
};

/** The dataset with this id, or undefined. */
export const datasetById = (id: string): DatasetEntry | undefined => (Object.hasOwn(DATASETS, id) ? DATASETS[id] : undefined);

